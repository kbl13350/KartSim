// Table returns the probability table of kind (TableIndividual, TableTeam,
// TableIndiChanger, TableTeamChanger).
func (d *Data) Table(kind string) *Table { return d.Tables[kind] }

// Item returns a table item.
func (d *Data) Item(idx int) (Item, bool) {
	item, ok := d.items[idx]
	return item, ok
}

// Cap returns how many times a racer can get idx in one race; ok is false
// for an item the restriction does not limit.
func (d *Data) Cap(idx int) (allowCount int, ok bool) {
	allowCount, ok = d.caps[idx]
	return allowCount, ok
}

// Track returns an item room track.
func (d *Data) Track(id string) (Track, bool) {
	track, ok := d.tracks[id]
	return track, ok
}

// Pool returns the tracks of a random-track code (nil for a code item rooms
// do not accept).
func (d *Data) Pool(code int) []string { return d.pools[code] }

// Passive returns the item-race chance (percent, 0 when none) of a passive
// attribute of the item itemID held as holder (HolderKart, …).
func (d *Data) Passive(holder string, itemID int, attribute string) int {
	return d.passives[holder][itemID][attribute]
}

// XunKart reports whether kart is a 迅 item kart (it starts holding an item).
func (d *Data) XunKart(kart int) bool { return d.xun[kart] }

var loadDefault = sync.OnceValues(func() (*Data, error) { return Parse(embedded) })

// Default returns the embedded data, parsed once.
func Default() (*Data, error) { return loadDefault() }
