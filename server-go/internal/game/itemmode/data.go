// Package itemmode holds the rules of the item races (道具个人赛 / 组队道具赛,
// rewrite/ITEM_MODE.md) that the game node enforces: the original
// rank-group probability tables and per-race caps, item slots, target
// selection, item timelines, slot locks, scans and the cube anti-abuse
// check, and (appendix C) the per-kart item tables, the special items they
// lead to, the equipment passives a victim may claim, the item changer
// cards, the in-race lucci and the result titles. It is pure: callers pass
// the time, the standings and the random source, and turn the results into
// protocol events.
//
// itemmode.json is generated by rewrite/tools/export-item-mode-data.mjs and
// embedded here; never edit it by hand (version_test.go recomputes its
// content version).
package itemmode

